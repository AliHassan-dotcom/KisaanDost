def mine_and_save_raw_data(output_path="d:/KisaanDost/Kisaan_Dost_Data/raw/web_collected_pest_data.csv"):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    keys = RAW_PEST_RECORDS[0].keys()
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows(RAW_PEST_RECORDS)
    print(f"[OK] Extracted {len(RAW_PEST_RECORDS)} verified surveillance records to {output_path}")

if __name__ == "__main__":
    mine_and_save_raw_data()
